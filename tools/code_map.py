"""Generate or check a source-grounded map of Cluster Desk's Python modules."""
import argparse
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'docs' / 'code-maps' / 'cluster-desk.md'


def inputs():
    """Select runtime modules, excluding tests and the Windows-only smoke tool."""
    return sorted(path for path in ROOT.glob('*.py')
                  if not path.name.startswith('test_') and path.name != 'smoke_packaged.py')


def describe(node):
    """Use an existing docstring's first line without inventing an intent."""
    doc = ast.get_docstring(node)
    return doc.splitlines()[0].strip().replace('|', r'\|') if doc else 'Not documented'


def generate():
    """Build a deterministic Markdown inventory from the selected source files."""
    files = inputs()
    names = {path.stem for path in files}
    digest = hashlib.sha256()
    parsed = []
    for path in files:
        # Git checkouts may use CRLF or LF; line endings must not stale the map.
        data = path.read_bytes().replace(b'\r\n', b'\n')
        digest.update(path.name.encode('utf-8') + b'\0' + data + b'\0')
        parsed.append((path, ast.parse(data, filename=str(path))))

    lines = [
        '<!-- Generated by tools/code_map.py. Do not edit by hand. -->',
        '# Cluster Desk code map', '',
        f'- Source fingerprint: `{digest.hexdigest()}`',
        '- Generate: `python tools/code_map.py`',
        '- Check: `python tools/code_map.py --check`',
        '- Scope: root-level runtime Python modules; tests, tools, generated files and bundled third-party references are excluded.', '',
        '## Module dependencies', '',
        'Static imports of another in-scope module, including conditional imports; these edges do not prove that a path executes.', '',
        '| Module | Local imports | Purpose (module docstring) |', '|---|---|---|',
    ]
    for path, tree in parsed:
        imports = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports.update(alias.name.split('.')[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imports.add(node.module.split('.')[0])
        imports &= names
        deps = ', '.join(f'`{name}`' for name in sorted(imports)) or '—'
        lines.append(f'| [{path.name}](../../{path.name}) | {deps} | {describe(tree)} |')

    lines += ['', '## Functions and methods', '',
              'Names and line links are parsed from source. Purpose is the first line of an existing docstring; “Not documented” identifies a gap, not a behavioral description. Nested functions are omitted.', '']
    for path, tree in parsed:
        entries = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                entries.append((node.name, node))
            elif isinstance(node, ast.ClassDef):
                entries.append((node.name + ' (class)', node))
                entries.extend((node.name + '.' + child.name, child) for child in node.body
                               if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)))
        if not entries:
            continue
        lines += [f'### {path.name}', '', '| Symbol | Purpose |', '|---|---|']
        for name, node in entries:
            lines.append(f'| [`{name}`](../../{path.name}#L{node.lineno}) | {describe(node)} |')
        lines.append('')
    lines += ['## Limits', '',
              '- Static imports do not capture dynamic imports, call graphs, runtime state, user choices, or network behavior.',
              '- Class methods and module-level functions are listed; nested callbacks, inherited methods and generated code are not.',
              '- The fingerprint ignores CRLF versus LF but detects other changes to included modules, including comments.',
              '- Read the actual source and tests before relying on a map for behavior or compatibility.', '']
    return '\n'.join(lines)


def main():
    """Write the map, or exit unsuccessfully when the checked-in map is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
            parser.exit(1, 'Code map is missing or stale; run python tools/code_map.py\n')
        print('Code map is fresh.')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
